import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const backstageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repositoryRoot = resolve(backstageRoot, '..', '..', '..');
const projectsRoot = join(repositoryRoot, 'projects');
const output = join(
  backstageRoot,
  'packages',
  'app',
  'src',
  'plugins',
  'ccus-screen-designs',
  'generatedProjectRegistry.ts',
);

const projects = [
  {
    projectId: 'CCUS-PLATFORM',
    projectName: 'CCUS Platform',
    description: 'Resonance 기반 탄소배출·LCA·감축·거래 통합 플랫폼',
    owner: 'ccus-platform-team',
    lifecycle: 'production',
    compatibilityClass: 'RESONANCE_NATIVE',
    sourcePath: 'projects/carbonet-frontend',
    metadataPath: 'projects/carbonet-backend-metadata',
    assetPath: 'projects/carbonet-assets',
    databaseMode: 'SHARED_HA_DATABASE',
    databaseSchema: 'public',
    runtimeMode: 'KUBERNETES',
    runtimeStatus: 'RUNNING',
    runtimeRoute: 'http://172.16.1.232',
    designRoute: '/ccus-screen-designs',
    screenSpaceRoute: '/ccus-screen-space',
    integrationStatus: 'CONNECTED',
  },
];

for (const entry of readdirSync(projectsRoot, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const manifestPath = join(projectsRoot, entry.name, 'manifest.json');
  try {
    const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
    const database = manifest.bindings?.database?.projectDb ?? {};
    projects.push({
      projectId: manifest.metadata.projectId,
      projectName: manifest.metadata.projectName,
      description: manifest.metadata.description ?? '',
      owner: manifest.metadata.owner ?? 'unknown',
      lifecycle: 'experimental',
      compatibilityClass:
        manifest.governance?.compatibilityClass ?? 'METADATA_FIRST',
      sourcePath: `projects/${entry.name}`,
      metadataPath: relative(repositoryRoot, manifestPath).replaceAll('\\', '/'),
      assetPath: `projects/${entry.name}`,
      databaseMode: manifest.bindings?.database?.bindingMode ?? 'UNBOUND',
      databaseSchema: database.schema ?? 'public',
      runtimeMode: manifest.runtime?.runtimeMode ?? 'UNASSIGNED',
      runtimeStatus: manifest.runtime?.status ?? 'UNKNOWN',
      runtimeRoute: manifest.runtime?.routing?.routePrefix ?? '',
      designRoute: '/ccus-screen-designs',
      screenSpaceRoute: '/ccus-screen-space',
      integrationStatus:
        manifest.runtime?.status === 'RUNNING' ? 'CONNECTED' : 'SEPARATED',
    });
  } catch {
    // Directories without a valid project manifest are framework assets.
  }
}

projects.sort((a, b) => a.projectId.localeCompare(b.projectId));
const generated = `// Generated by scripts/generate-resonance-project-registry.mjs. Do not edit.
export type ResonanceProjectRecord = {
  projectId: string;
  projectName: string;
  description: string;
  owner: string;
  lifecycle: string;
  compatibilityClass: string;
  sourcePath: string;
  metadataPath: string;
  assetPath: string;
  databaseMode: string;
  databaseSchema: string;
  runtimeMode: string;
  runtimeStatus: string;
  runtimeRoute: string;
  designRoute: string;
  screenSpaceRoute: string;
  integrationStatus: string;
};
export const RESONANCE_PROJECT_REGISTRY: ResonanceProjectRecord[] = ${JSON.stringify(
  projects,
  null,
  2,
)};
`;
writeFileSync(output, generated, 'utf8');
console.log(`[project-registry] wrote ${projects.length} projects to ${output}`);
