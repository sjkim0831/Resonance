const { chromium } = require('/opt/Resonance/projects/carbonet-frontend/source/node_modules/playwright');
const fs = require('node:fs');
const output=process.env.OUTPUT_DIR||'/opt/resonance-data/backups/ccus-unification-20260906';
(async()=>{
 const base=process.env.BASE_URL||'http://127.0.0.1:32100';
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const failures=[], requests=[];
 page.on('request',r=>{if(new URL(r.url()).pathname==='/api/home')requests.push(r.url())});
 page.on('pageerror',e=>failures.push(e.message));
 const font=await page.request.get(base+'/assets/react/assets/fonts/MaterialSymbolsOutlined-0.46.0.woff2');
 if(!font.ok() || (await font.body()).subarray(0,4).toString()!=='wOF2') failures.push('ICON_FONT_MISSING_OR_INVALID');
 const api=await page.request.get(base+'/api/home');
 const data=await api.json();
 if(!api.ok()||!data.homeMenu?.length)failures.push('MENU_API_EMPTY');
 await page.goto(base+'/home',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.querySelectorAll('[data-global-user-gnb] nav .gnb-item').length>0,{},{timeout:20000}).catch(()=>failures.push('HEADER_MENU_MISSING'));
 await page.evaluate(()=>document.fonts.ready);
 const fontLoaded=await page.evaluate(()=>document.fonts.check('24px "Material Symbols Outlined"'));
 if(!fontLoaded)failures.push('ICON_FONT_NOT_LOADED');
 const rendered=await page.locator('[data-global-user-gnb] nav .gnb-item').count();
 if(rendered!==data.homeMenu?.length)failures.push('MENU_COUNT_MISMATCH');
 await page.waitForTimeout(2000);
 if(requests.length>6)failures.push('MENU_REQUEST_LOOP');
 await page.screenshot({path:output+'/header-desktop.png',fullPage:false});
 await page.setViewportSize({width:390,height:844});
 const mobile=page.locator('[data-global-user-gnb] button[aria-controls="global-mobile-menu"]');
 if(!await mobile.isVisible())failures.push('MOBILE_MENU_BUTTON_HIDDEN');
 await mobile.click();
 if(!await page.locator('#global-mobile-menu').isVisible())failures.push('MOBILE_MENU_CANNOT_OPEN');
 await page.screenshot({path:output+'/header-mobile.png'});
 const result={base,apiMenus:data.homeMenu?.length,rendered,fontLoaded,homeRequests:requests.length,failures};
 fs.writeFileSync(output+'/header-verification.json',JSON.stringify(result,null,2));
 console.log(JSON.stringify(result));await browser.close();process.exitCode=failures.length?1:0;
})().catch(e=>{console.error(e);process.exitCode=1});
